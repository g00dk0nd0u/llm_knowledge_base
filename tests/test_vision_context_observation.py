def test_real_db_pdf_png_inputs_are_unchanged_and_observation_has_no_io(tmp_path, monkeypatch):
    source = make_context_case(tmp_path)
    result = render(source, dpi=72)
    image = output_file(source, result)
    v1_request = build_vision_context_inspection_request(result, image, 'Inspect 電気錠')
    paths = (source['database'], source['pdf'], image)
    before = {path: (path.read_bytes(), path.stat().st_mtime_ns) for path in paths}
    files = sorted(tmp_path.rglob('*'))
    def forbid_read(*args, **kwargs):
        raise AssertionError('observation contracts must not perform file I/O')
    with monkeypatch.context() as blocked:
        blocked.setattr(Path, 'read_bytes', forbid_read)
        blocked.setattr(Path, 'read_text', forbid_read)
        blocked.setattr(Path, 'write_bytes', forbid_read)
        blocked.setattr(Path, 'write_text', forbid_read)
        for status in STATUSES:
            value = build(v1_request, 'p', 'm', TEXT, status, provider_run_id='run')
            assert validate(value) == value
        with pytest.raises(VisionContractError):
            build(v1_request, 'p', 'm', TEXT, 'supported')
    assert before == {path: (path.read_bytes(), path.stat().st_mtime_ns) for path in paths}
    assert sorted(tmp_path.rglob('*')) == files


