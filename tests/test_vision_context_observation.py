def canonical(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=False,
                      separators=(',', ':'), allow_nan=False)


def content_id(prefix, envelope, field):
    content = {key: value for key, value in envelope.items() if key != field}
    return prefix + hashlib.sha256(canonical(content).encode('utf-8')).hexdigest()


def schema_accepts(value, *, with_format=True):
    jsonschema.validate(value, SCHEMA,
                        format_checker=jsonschema.FormatChecker() if with_format else None)


