def test_nested_request_deep_copy_and_tamper_rejection(v1_request, observation):
    before = deepcopy(observation)
    v1_request['document']['source_sha256'] = '4'*64
    v1_request['evidence_bbox'][0] += 1
    v1_request['renderer']['library_version'] = 'mutated'
    v1_request['clamped_edges'].append('left')
    assert observation == before
    isolated = validate(observation)
    isolated['request']['document']['id'] = 'mutated'
    isolated['request']['context_bbox'][0] += 1
    assert observation == before
    with pytest.raises(VisionContractError):
        validate(isolated)
    # Rehashing only the observation cannot bypass nested request validation.
    isolated['observation_id'] = content_id('vision-context-observation-', isolated, 'observation_id')
    with pytest.raises(VisionContractError, match='request ID mismatch|fixed margin'):
        validate(isolated)
    changed = deepcopy(observation)
    changed['observation'] += 'tampered'
    with pytest.raises(VisionContractError, match='observation ID mismatch'):
        validate(changed)


